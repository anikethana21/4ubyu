-- 4 U By U — Supabase schema
-- Run this once in the Supabase SQL Editor (Dashboard -> SQL -> New query).
--
-- The backend uses a single server-side Supabase client (core/db.py) with
-- SUPABASE_KEY. Use your project's *service_role* key here and keep it secret
-- (never in the browser). Row Level Security is therefore disabled on these
-- tables — access is already scoped by the app using the authenticated user_id.

-- ---------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------
create table if not exists public.users (
    id            uuid primary key,
    email         text unique not null,
    password_hash text not null,
    token_version integer not null default 1,
    created_at    timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- user_settings  (encrypted BYOK vault; one row per user)
-- ---------------------------------------------------------------------------
create table if not exists public.user_settings (
    user_id              uuid primary key references public.users(id) on delete cascade,
    default_model        text default 'openai/gpt-oss-120b',
    preferred_theme      text default 'dark_academic',
    encrypted_groq_key   text,
    encrypted_gemini_key text,
    encrypted_eraser_key text,
    created_at           timestamptz not null default now(),
    updated_at           timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- workspaces  (saved handbooks)
-- ---------------------------------------------------------------------------
create table if not exists public.workspaces (
    id            uuid primary key,
    user_id       uuid not null references public.users(id) on delete cascade,
    youtube_url   text,
    video_id      text,
    video_title   text,
    channel_name  text default 'YouTube',
    duration      text default '00:00',
    chapter_count integer default 0,
    status        text default 'completed',
    storage_path  text,
    created_at    timestamptz not null default now()
);

create index if not exists workspaces_user_id_idx on public.workspaces (user_id, created_at desc);

-- ---------------------------------------------------------------------------
-- token_blacklist  (revoked JWT JTIs on logout)
-- ---------------------------------------------------------------------------
create table if not exists public.token_blacklist (
    id         bigint generated by default as identity primary key,
    jti        text not null,
    user_id    uuid,
    expires_at timestamptz,
    created_at timestamptz not null default now()
);

create index if not exists token_blacklist_jti_idx on public.token_blacklist (jti);

-- ---------------------------------------------------------------------------
-- Storage bucket for saved handbook HTML
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('workspaces', 'workspaces', false)
on conflict (id) do nothing;

-- ---------------------------------------------------------------------------
-- Row Level Security: OFF (backend uses the service_role key)
-- ---------------------------------------------------------------------------
alter table public.users           disable row level security;
alter table public.user_settings   disable row level security;
alter table public.workspaces      disable row level security;
alter table public.token_blacklist disable row level security;
