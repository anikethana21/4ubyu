#!/usr/bin/env node
/**
 * Build the two things a user can install, from the same tested sources.
 *
 * The program is split in two for one reason: the half that decides what the notes
 * say is a set of plain modules that `npm test` can run with no browser, no key and
 * no network, and the half that reads YouTube's own player data is impossible to
 * test anywhere except inside YouTube. This script puts them back together.
 *
 *   node extension/build.js            write both builds
 *   node extension/build.js --check    exit non-zero if either build is stale
 *
 * What it writes, and why there:
 *
 *   - `4ubyu.user.js` at the repository root. This is the userscript, and the root
 *     is where GitHub Pages serves it from, which is what makes the `@updateURL`
 *     in its header work: a script manager that has installed it can see when a
 *     new version exists without anyone asking the user to do anything.
 *   - `extension/dist/store/` — the same program as a Chrome extension: a manifest,
 *     a content script, and a service worker. The only differences are the three
 *     script-manager functions at the top of the content script, so the notes are
 *     written by exactly the code the tests ran.
 *
 * The modules are wrapped in a function that shadows `module` and `require`. Each
 * of them is also a CommonJS module, and a page is free to have a global named
 * `module` of its own — without the wrapper, a page that happens to define one
 * would send the pipeline down a branch where `require` does not exist.
 */

const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const EXTENSION = __dirname;
const ROOT = path.join(EXTENSION, "..");
const SHELL = path.join(EXTENSION, "userscript.js");
const USERSCRIPT_OUT = path.join(ROOT, "4ubyu.user.js");
const STORE_DIR = path.join(EXTENSION, "dist", "store");
const ICON_DIR = path.join(EXTENSION, "assets", "icons");
const ICONS = ["icon16.png", "icon32.png", "icon48.png", "icon128.png"];

// The store's summary field and the manifest's description are the same 132
// characters, so this is a whole sentence on purpose: the userscript's own
// description is longer, and slicing it mid-word read like a typo in the one
// place a person decides whether to install.
const STORE_SUMMARY =
  "Turn the YouTube lecture you are watching into topic-wise study notes. " +
  "Your own API key, one HTML file. No account, no server.";

const MARKER = "  // <<<UBYU_MODULES>>>";

/** In dependency order: each of these reads the ones above it. */
const MODULES = ["core.js", "markdown.js", "assets.js", "workspace.js", "pipeline.js", "panel.js"];

function read(file) {
  return fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");
}

function headerOf(shell) {
  const end = shell.indexOf("*/\n");
  if (!shell.startsWith("// ==UserScript==") || end < 0) {
    throw new Error("extension/userscript.js does not begin with a userscript metadata block");
  }
  const header = shell.slice(0, end);
  const version = (header.match(/^\/\/ @version\s+(\S+)/m) || [])[1];
  const description = (header.match(/^\/\/ @description\s+(.+)$/m) || [])[1];
  const name = (header.match(/^\/\/ @name\s+(.+)$/m) || [])[1];
  if (!version || !description || !name) {
    throw new Error("the userscript header needs @name, @version and @description");
  }
  return { header, version, description: description.trim(), name: name.trim() };
}

function buildUserScript() {
  const shell = read(SHELL);
  if (!shell.includes(MARKER)) {
    throw new Error(`extension/userscript.js has no ${MARKER} line to fold the modules into`);
  }

  const parts = [];
  for (const name of MODULES) {
    const file = path.join(EXTENSION, "src", name);
    if (!fs.existsSync(file)) {
      throw new Error(`missing module: src/${name} (run \`npm run assets\` for assets.js)`);
    }
    parts.push(`/* ---- src/${name} ---- */\n${read(file).trimEnd()}`);
  }

  const folded = [
    "  // -------------------------------------------------------------------------",
    "  // The pipeline, folded in by extension/build.js.",
    "  //",
    "  // These are the same files the tests run against and the same ones dev/run.js",
    "  // loads. Do not edit them here: edit extension/src/*.js and run `npm run build`.",
    "  // -------------------------------------------------------------------------",
    "  (function (module, exports, require) {",
    parts.join("\n\n"),
    "  })(undefined, undefined, undefined);",
  ].join("\n");

  // A function replacement, not a string: the pipeline's own source contains
  // sequences like `` $` `` inside its regular expressions, and those mean
  // something else to String.replace.
  const built = shell.replace(MARKER, () => folded.trimEnd());
  const meta = headerOf(shell);
  const start = built.indexOf("*/\n") + 3;
  const banner =
    "// Generated by extension/build.js from extension/userscript.js and extension/src/*.js.\n" +
    "// Edit the sources, not this file. `npm run build` rewrites it; `npm run build:check`\n" +
    "// fails if this copy is out of date.\n";

  // The banner goes under the metadata block, because a userscript header only
  // counts when it is the first thing in the file.
  return { text: built.slice(0, start) + banner + built.slice(start), version: meta.version };
}

/**
 * The same program as a Chrome extension.
 *
 * A content script cannot use `GM_*`, so the four functions the shell asks for are
 * provided here instead. Two of them are worth a note:
 *
 *   - The store. `chrome.storage` is asynchronous and the pipeline's cache is read
 *     synchronously, so everything is copied into memory once at start-up and read
 *     from there; writes go to both. A run resumed after a closed tab still finds
 *     its finished sections, because they were written through.
 *   - The request. A content script's `fetch` is subject to the page's own
 *     Content-Security-Policy, and YouTube's is not always friendly. So the panel
 *     asks the page first and falls back to `GM_xmlhttpRequest`, which here is a
 *     message to the service worker — out of the page's reach, and the reason the
 *     manifest asks for permission to reach the provider.
 */
function buildStore(version, name, description) {
  const { text } = buildUserScript();
  const body = text.slice(text.indexOf("*/\n") + 3).replace(/^\/\/ Generated[\s\S]*?out of date\.\n/, "");

  const content = `// Generated by extension/build.js. Edit extension/src/*.js and rebuild.
(function () {
  "use strict";

  // chrome.storage is asynchronous; the pipeline reads its cache synchronously.
  const memory = new Map();
  const waiting = [];

  function GM_getValue(key, fallback) {
    return memory.has(key) ? memory.get(key) : fallback;
  }
  function GM_setValue(key, value) {
    memory.set(key, value);
    chrome.storage.local.set({ [key]: value });
  }
  function GM_deleteValue(key) {
    memory.delete(key);
    chrome.storage.local.remove(key);
  }
  function GM_registerMenuCommand(label, run) {
    // An extension has no script-manager menu. The panel's own button is the way
    // in, so this only remembers what was offered, for the record.
    waiting.push({ label, run });
  }
  function GM_openInTab(url) {
    window.open(url, "_blank", "noopener");
  }
  function GM_xmlhttpRequest(options) {
    chrome.runtime.sendMessage(
      {
        type: "ubyu:request",
        url: options.url,
        method: options.method || "GET",
        headers: options.headers || {},
        data: options.data,
      },
      (reply) => {
        if (chrome.runtime.lastError) {
          if (options.onerror) options.onerror(new Error(chrome.runtime.lastError.message));
          return;
        }
        if (!reply || !reply.ok) {
          if (options.onerror) options.onerror(new Error((reply && reply.error) || "the request failed"));
          return;
        }
        if (options.onload) options.onload({ status: reply.status, responseText: reply.text });
      }
    );
  }

  function start() {
${body.trimEnd()}
  }

  chrome.storage.local.get(null, (all) => {
    for (const key of Object.keys(all || {})) memory.set(key, all[key]);
    start();
  });
})();
`;

  const background = `// Generated by extension/build.js. The extension's one job that the page cannot
// do for itself: make the provider request from somewhere the page's
// Content-Security-Policy cannot reach.
chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {
  if (!message || message.type !== "ubyu:request") return false;
  fetch(message.url, {
    method: message.method,
    headers: message.headers,
    body: message.data,
  })
    .then(async (response) => sendResponse({ ok: true, status: response.status, text: await response.text() }))
    .catch((error) => sendResponse({ ok: false, error: String((error && error.message) || error) }));
  return true;
});
`;

  const manifest = {
    manifest_version: 3,
    name,
    version,
    // The store's summary field and the manifest's description are the same
    // 132 characters, and they are a whole sentence: the userscript's own
    // description is longer, and slicing it mid-word looked like a typo in the
    // one place a person decides whether to install.
    description: STORE_SUMMARY.slice(0, 132),
    // The store draws the mark at 128, the extensions page at 48, the toolbar at
    // 32 and 16. All four are rasterised from assets/icon.svg by tools/icons.js.
    icons: {
      16: "icons/icon16.png",
      32: "icons/icon32.png",
      48: "icons/icon48.png",
      128: "icons/icon128.png",
    },
    // Where a reviewer, or anyone who wonders what this is, can read about it.
    homepage_url: "https://anikethana21.github.io/4ubyu/",
    // No remote code, no analytics, no account: the only permission that reaches
    // out of the browser is the one that lets the service worker ask the provider
    // the user chose for the notes the user asked for.
    permissions: ["storage"],
    host_permissions: ["https://www.youtube.com/*", "https://api.groq.com/*"],
    minimum_chrome_version: "111",
    background: { service_worker: "background.js" },
    content_scripts: [
      // The page's own world first, and as early as it can run: it is the only
      // place YouTube's player objects exist, and the isolated script asks it for
      // them by name. `page-bridge.js` is the file in extension/ of that name.
      {
        matches: ["https://www.youtube.com/*"],
        js: ["page-bridge.js"],
        run_at: "document_start",
        world: "MAIN",
      },
      {
        matches: ["https://www.youtube.com/*"],
        js: ["content.js"],
        run_at: "document_idle",
      },
    ],
  };

  return {
    "content.js": content,
    "page-bridge.js": read(path.join(EXTENSION, "page-bridge.js")),
    "background.js": background,
    "manifest.json": JSON.stringify(manifest, null, 2) + "\n",
  };
}

function main() {
  const check = process.argv.includes("--check");
  const { text, version } = buildUserScript();
  const meta = headerOf(read(SHELL));
  const store = buildStore(version, meta.name, meta.description);

  const bytes = Buffer.byteLength(text, "utf8");
  const sha = crypto.createHash("sha256").update(text).digest("hex").slice(0, 12);
  const outputs = [
    { file: path.relative(ROOT, USERSCRIPT_OUT), text, note: `v${version}, ${Math.round(bytes / 1024)} KB, sha256:${sha}` },
    ...Object.entries(store).map(([name, body]) => ({
      file: path.join("extension", "dist", "store", name),
      text: body,
      note: `${Math.round(Buffer.byteLength(body, "utf8") / 1024)} KB`,
    })),
    // The icons are binary, so they are copied rather than written as text, and
    // compared byte for byte in --check.
    ...ICONS.map((name) => {
      const data = fs.readFileSync(path.join(ICON_DIR, name));
      return {
        file: path.join("extension", "dist", "store", "icons", name),
        data,
        note: `${Math.round(data.length / 1024)} KB`,
      };
    }),
  ];

  if (check) {
    const stale = outputs.filter((output) => {
      const file = path.join(ROOT, output.file);
      if (!fs.existsSync(file)) return true;
      const actual = fs.readFileSync(file);
      return output.data ? !actual.equals(output.data) : actual.toString("utf8") !== output.text;
    });
    if (stale.length) {
      console.error(`stale build output — run \`npm run build\`: ${stale.map((s) => s.file).join(", ")}`);
      process.exit(1);
    }
    console.log(`builds are current — userscript ${outputs[0].note}, store package v${version}`);
    return;
  }

  for (const output of outputs) {
    const file = path.join(ROOT, output.file);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, output.data || output.text);
    console.log(`wrote ${output.file} — ${output.note}`);
  }
}

main();
