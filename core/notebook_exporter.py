"""
Export generated chapters to Jupyter Notebook (.ipynb) format.
Each chapter becomes markdown cells; code blocks become executable code cells.
"""

import json
from pathlib import Path
from typing import List, Dict, Any, Optional
from datetime import datetime

try:
    import nbformat as nbf
    NBF_AVAILABLE = True
except ImportError:  # pragma: no cover
    NBF_AVAILABLE = False

from config import BASE_DIR, OUTPUT_DIR


class NotebookExporter:
    """Exports chapter contents to a Jupyter notebook."""

    def __init__(self, notebook_dir: Optional[Path] = None):
        self.nb_dir = Path(notebook_dir) if notebook_dir else (BASE_DIR / "output" / "notebooks")
        self.nb_dir.mkdir(parents=True, exist_ok=True)

    def chapters_to_notebook(
        self,
        chapters: List[Dict[str, Any]],
        metadata: Dict[str, Any],
        filename: Optional[str] = None,
    ) -> str:
        """
        Build an .ipynb from ChapterContent structures (phase 5/6 output).
        Returns the written file path.
        """
        if not NBF_AVAILABLE:
            raise RuntimeError("nbformat is required: pip install nbformat")

        nb = nbf.v4.new_notebook()
        nb.metadata["authors"] = [{"name": "4 U By U"}]
        nb.metadata["kernelspec"] = {
            "display_name": "Python 3",
            "language": "python",
            "name": "python3",
        }
        nb.metadata["language_info"] = {"name": "python"}

        title = metadata.get("title", "Untitled")
        channel = metadata.get("channel", "Unknown")
        video_id = metadata.get("video_id", "")
        duration = metadata.get("duration", "")

        header = f"# {title}\n\n"
        header += f"**Channel:** {channel}  \n"
        if duration:
            header += f"**Duration:** {duration}  \n"
        if video_id:
            header += f"**Video:** https://www.youtube.com/watch?v={video_id}\n\n"
        header += "*Generated by 4 U By U — interactive study notebook*"
        nb.cells.append(nbf.v4.new_markdown_cell(header))

        # Table of contents
        toc_lines = ["## Table of Contents\n"]
        for i, ch in enumerate(chapters, start=1):
            ch_title = ch.get("chapter_title") or ch.get("title", f"Chapter {i}")
            toc_lines.append(f"{i}. {ch_title}")
        nb.cells.append(nbf.v4.new_markdown_cell("\n".join(toc_lines)))

        for i, ch in enumerate(chapters, start=1):
            ch_title = ch.get("chapter_title") or ch.get("title", f"Chapter {i}")
            ts = ch.get("timestamp_str", "00:00")
            vid = metadata.get("video_id", "")

            link = ""
            if vid and ch.get("timestamp_seconds") is not None:
                link = (
                    f" [▶ {ts}](https://www.youtube.com/watch?v={vid}"
                    f"&t={int(ch.get('timestamp_seconds') or 0)}s)"
                )
            nb.cells.append(nbf.v4.new_markdown_cell(f"## Chapter {i}: {ch_title}{link}"))

            overview = ch.get("overview", "")
            if overview:
                nb.cells.append(nbf.v4.new_markdown_cell(f"### Overview\n\n{overview}"))

            for sec in ch.get("sections", []):
                sec_title = sec.get("section_title") or sec.get("title") or ""
                if sec_title:
                    sec_ts = sec.get("time_reference", "")
                    suffix = f"  `[{sec_ts}]`" if sec_ts else ""
                    nb.cells.append(nbf.v4.new_markdown_cell(f"### {sec_title}{suffix}"))

                theory = sec.get("theory_block") or {}
                explanation = theory.get("explanation", "") if isinstance(theory, dict) else ""
                if explanation:
                    nb.cells.append(nbf.v4.new_markdown_cell(explanation))

                for cb in sec.get("code_blocks", []) or []:
                    code = cb.get("code", "")
                    if code and code.strip():
                        nb.cells.append(nbf.v4.new_code_cell(code))

                diagrams = sec.get("visual_diagrams", []) or []
                for d in diagrams:
                    if not isinstance(d, dict):
                        continue
                    caption = d.get("caption", "")
                    mermaid = d.get("mermaid") or d.get("diagram", "")
                    if mermaid:
                        nb.cells.append(
                            nbf.v4.new_markdown_cell(
                                f"```mermaid\n{mermaid}\n```\n\n*{caption}*" if caption
                                else f"```mermaid\n{mermaid}\n```"
                            )
                        )

                key_points = sec.get("key_points", []) or []
                if key_points:
                    kp_text = "\n".join(f"- {kp}" for kp in key_points)
                    nb.cells.append(nbf.v4.new_markdown_cell(f"**Key Points**\n\n{kp_text}"))

                pitfalls = sec.get("pitfalls", []) or []
                if pitfalls:
                    p_text = "\n".join(f"- {p}" for p in pitfalls)
                    nb.cells.append(nbf.v4.new_markdown_cell(f"**Pitfalls**\n\n{p_text}"))

            summary = ch.get("chapter_summary", "")
            if summary:
                nb.cells.append(nbf.v4.new_markdown_cell(f"### Summary\n\n{summary}"))

        if not filename:
            vid = metadata.get("video_id") or "unknown"
            stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            filename = f"notes_{vid}_{stamp}.ipynb"

        out_path = self.nb_dir / filename
        with open(out_path, "w", encoding="utf-8") as f:
            nbf.write(nb, f)

        print(f"[NotebookExporter] Saved notebook to {out_path}")
        return str(out_path)


class HandbookNotebookConverter:
    """Converts an existing generated tri-pane HTML handbook into an .ipynb."""

    @staticmethod
    def html_to_notebook(html_path: Path, out_path: Optional[Path] = None) -> str:
        if not NBF_AVAILABLE:
            raise RuntimeError("nbformat is required: pip install nbformat")
        try:
            from bs4 import BeautifulSoup
        except ImportError:
            raise RuntimeError("beautifulsoup4 is required: pip install beautifulsoup4")

        html = Path(html_path).read_text(encoding="utf-8", errors="ignore")
        soup = BeautifulSoup(html, "html.parser")

        video_id = ""
        meta_vid = soup.find("meta", attrs={"name": "video-id"})
        if meta_vid:
            video_id = meta_vid.get("content", "")
        page_title = (soup.title.string if soup.title else "Study Notes").split("—")[0].strip()

        nb = nbf.v4.new_notebook()
        nb.metadata["authors"] = [{"name": "4 U By U"}]
        nb.metadata["kernelspec"] = {
            "display_name": "Python 3",
            "language": "python",
            "name": "python3",
        }
        nb.metadata["language_info"] = {"name": "python"}

        header = f"# {page_title}\n\n"
        if video_id:
            header += f"**Video:** https://www.youtube.com/watch?v={video_id}\n\n"
        header += "*Exported from a 4 U By U interactive workspace*"
        nb.cells.append(nbf.v4.new_markdown_cell(header))

        articles = soup.find_all("article", class_="chapter-card")
        toc = ["## Table of Contents\n"] + [
            f"{i}. {a.get('data-chapter-title', f'Chapter {i}')}"
            for i, a in enumerate(articles, 1)
        ]
        if len(articles) > 1:
            nb.cells.append(nbf.v4.new_markdown_cell("\n".join(toc)))

        for i, art in enumerate(articles, start=1):
            ch_title = art.get("data-chapter-title", f"Chapter {i}")
            try:
                ts_sec = int(float(art.get("data-timestamp-seconds", "0")))
            except (TypeError, ValueError):
                ts_sec = 0
            link = ""
            if video_id:
                m, s = divmod(ts_sec, 60)
                link = f" [▶ {m:02d}:{s:02d}](https://www.youtube.com/watch?v={video_id}&t={ts_sec}s)"
            nb.cells.append(nbf.v4.new_markdown_cell(f"## Chapter {i}: {ch_title}{link}"))

            overview = art.find("p", class_="chapter-overview")
            if overview:
                nb.cells.append(nbf.v4.new_markdown_cell(f"### Overview\n\n{overview.get_text(' ', strip=True)}"))

            for sec in art.find_all("section", class_="section-block"):
                heading = sec.find("h3", class_="section-heading")
                if heading:
                    nb.cells.append(nbf.v4.new_markdown_cell(f"### {heading.get_text(strip=True)}"))

                theory = sec.find("div", class_="theory-content")
                if theory:
                    # Strip nested interactive controls (copy buttons, badges) before text
                    for bad in theory.find_all(["button", "svg"]):
                        bad.decompose()
                    txt = theory.get_text("\n", strip=True)
                    if txt:
                        nb.cells.append(nbf.v4.new_markdown_cell(txt))

                for code_el in sec.find_all("code"):
                    code = code_el.get_text()
                    if code and code.strip() and len(code) > 10:
                        nb.cells.append(nbf.v4.new_code_cell(code))

                kp = sec.find("div", class_="keypoints-card")
                if kp:
                    items = [li.get_text(" ", strip=True) for li in kp.find_all("li")]
                    if not items:
                        items = [
                            l.strip() for l in kp.get_text("\n", strip=True).split("\n")
                            if l.strip() and not l.strip().startswith("Key")
                        ]
                    if items:
                        body = "\n".join(f"- {x}" for x in items)
                        nb.cells.append(nbf.v4.new_markdown_cell(f"**Key Points**\n\n{body}"))

                for ex in sec.find_all("div", class_="example-card"):
                    ex_txt = ex.get_text(" ", strip=True)
                    if ex_txt:
                        nb.cells.append(nbf.v4.new_markdown_cell(f"**Example**\n\n{ex_txt}"))

            summary = art.find("div", class_="chapter-summary-footer")
            if summary:
                s_txt = summary.get_text(" ", strip=True)
                if s_txt:
                    nb.cells.append(nbf.v4.new_markdown_cell(f"### Summary\n\n{s_txt}"))

        if out_path is None:
            from datetime import datetime as _dt
            vid = video_id or "unknown"
            stamp = _dt.now().strftime("%Y%m%d_%H%M%S")
            out_path = Path(html_path).parent / "notebooks" / f"notes_{vid}_{stamp}.ipynb"
        out_path = Path(out_path)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            nbf.write(nb, f)

        print(f"[NotebookConverter] Wrote {len(nb.cells)} cells -> {out_path}")
        return str(out_path)


def export_state_to_notebook(state: Dict[str, Any]) -> Optional[str]:
    """Convenience: export from a MasterNotesState after pipeline completion."""
    chapters = state.get("chapter_contents") or []
    if not chapters:
        print("[NotebookExporter] No chapter_contents in state — skipping export.")
        return None
    meta = {
        "video_id": state.get("video_id", ""),
        "title": (state.get("video_metadata") or {}).get("title", "Untitled"),
        "channel": (state.get("video_metadata") or {}).get("channel", "Unknown"),
        "duration": (state.get("video_metadata") or {}).get("duration_str", ""),
    }
    exporter = NotebookExporter()
    return exporter.chapters_to_notebook(chapters, meta)
